/**
 * Stuntdouble Cross-Language Conformance — Fixture Generator
 * Copyright (c) 2026 Yusuf Günay. Licensed under MPL-2.0.
 *
 * Converts fixtures/scenarios.json (produced by emit-reference.mjs from the TypeScript
 * scenario corpus) into native, dependency-free literal tables for the C#, C++ and Lua
 * kernels. No runtime JSON parser is required on any side, which keeps the kernels
 * themselves zero-dependency and embeddable inside game mods.
 *
 * Usage: node packages/conformance/gen-fixtures.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const FIXTURES = join(HERE, 'fixtures');

const scenarios = JSON.parse(readFileSync(join(FIXTURES, 'scenarios.json'), 'utf8'));

const PRESENTATION = { TACTICAL: 0, CINEMATIC_LIVE: 1, CINEMATIC_RESOLVE: 2 };
const AUTONOMY = { FULL_COMBAT: 0, CO_PILOT: 1, GRIND_AUTOPILOT: 2, SHADOW_SURVIVAL: 3, COMMANDER: 4 };

/** Formats a JS number as a C-style double literal that round-trips exactly. */
const num = (v) => {
  const n = Number(v);
  if (!Number.isFinite(n)) throw new Error(`Non-finite number in fixtures: ${v}`);
  return Number.isInteger(n) ? `${n}.0` : String(n);
};

const hasAuto = (s) => typeof s.autonomy === 'string';
const autoIdx = (s) => (hasAuto(s) ? AUTONOMY[s.autonomy] : 0);

const csBool = (b) => (b ? 'true' : 'false');
const csStr = (s) => (s === null || s === undefined ? 'null' : `"${String(s).replace(/"/g, '\\"')}"`);

function csEntity(e, indent) {
  const p = e.position;
  const v = e.velocity ?? { x: 0, y: 0, z: 0 };
  return (
    `${indent}new EntitySnapshot { Id = ${csStr(e.id)}, Position = new Vec3(${num(p.x)}, ${num(p.y)}, ${num(p.z)}), ` +
    `Velocity = new Vec3(${num(v.x)}, ${num(v.y)}, ${num(v.z)}), ` +
    `HealthRatio = ${num(e.healthRatio)}, StaminaRatio = ${num(e.staminaRatio)}, ` +
    `IsAttacking = ${csBool(!!e.isAttacking)}, IsWindUp = ${csBool(!!e.isWindUp)}, ` +
    `IsRanged = ${csBool(!!e.isRanged)}, ${e.projectileEta ? `ProjectileEta = ${num(e.projectileEta)}, ` : ''}ThreatWeight = ${num(e.threatWeight)} }`
  );
}

function emitCs() {
  const blocks = scenarios
    .map((s) => {
      const p = s.profile;
      const hostiles = s.hostiles.length
        ? s.hostiles.map((h) => csEntity(h, '                    ')).join(',\n')
        : '';
      return `            new ScenarioFixture
            {
                Id = ${csStr(s.id)},
                Profile = new BehaviorProfile
                {
                    Id = ${csStr(p.id)},
                    Name = ${csStr(p.name ?? 'Protagonist')},
                    Aggression = ${num(p.aggression)},
                    Discipline = ${num(p.discipline)},
                    CinematicFlair = ${num(p.cinematicFlair)},
                    ReactionDelayMs = ${p.reactionDelayMs},
                    PreferredRange = ${num(p.preferredRange)}
                },
                Self = ${csEntity(s.self, '').replace(/^/, '')},
                Hostiles = new EntitySnapshot[]
                {
${hostiles}
                },
                Presentation = (PresentationMode)${PRESENTATION[s.presentation]},
                Autonomy = (AutonomyMode)${autoIdx(s)},
                HasAutonomy = ${csBool(hasAuto(s))},
                Behaviors = ${s.behaviors},
                HasWaypoint = ${csBool(!!s.waypoint)},
                Waypoint = new Vec3(${num(s.waypoint?.x ?? 0)}, ${num(s.waypoint?.y ?? 0)}, ${num(s.waypoint?.z ?? 0)})
            }`;
    })
    .join(',\n');

  return `// <auto-generated>Stuntdouble conformance fixtures — regenerate with: node packages/conformance/gen-fixtures.mjs</auto-generated>
// Copyright (c) 2026 Yusuf Günay. Licensed under MPL-2.0.
using Stuntdouble.Brain;

namespace Stuntdouble.Conformance
{
    public sealed class ScenarioFixture
    {
        public string Id;
        public BehaviorProfile Profile;
        public EntitySnapshot Self;
        public EntitySnapshot[] Hostiles;
        public PresentationMode Presentation;
        public AutonomyMode Autonomy;   // legacy preset (valid when HasAutonomy)
        public bool HasAutonomy;
        public int Behaviors;           // resolved flag mask
        public bool HasWaypoint;
        public Vec3 Waypoint;
    }

    public static class Fixtures
    {
        public static readonly ScenarioFixture[] All =
        {
${blocks}
        };
    }
}
`;
}

function cppEntity(e, indent) {
  const p = e.position;
  const v = e.velocity ?? { x: 0, y: 0, z: 0 };
  return (
    `${indent}stuntdouble::EntitySnapshot{${JSON.stringify(e.id)}, stuntdouble::Vec3{${num(p.x)}, ${num(p.y)}, ${num(p.z)}}, ` +
    `stuntdouble::Vec3{${num(v.x)}, ${num(v.y)}, ${num(v.z)}}, ${num(e.healthRatio)}, ${num(e.staminaRatio)}, ` +
    `${e.isAttacking ? 'true' : 'false'}, ${e.isWindUp ? 'true' : 'false'}, ${e.isRanged ? 'true' : 'false'}, ${num(e.threatWeight)}${e.projectileEta ? `, ${num(e.projectileEta)}` : ''}}`
  );
}

function emitCpp() {
  const blocks = scenarios
    .map((s) => {
      const p = s.profile;
      const hostiles = s.hostiles.length
        ? s.hostiles.map((h) => cppEntity(h, '                ')).join(',\n')
        : '';
      return `    stuntdouble::conformance::ScenarioFixture{
        ${JSON.stringify(s.id)},
        stuntdouble::BehaviorProfile{${num(p.aggression)}, ${num(p.discipline)}, ${num(p.cinematicFlair)}, ${p.reactionDelayMs}, ${num(p.preferredRange)}},
        ${cppEntity(s.self, '')},
        std::vector<stuntdouble::EntitySnapshot>{
${hostiles}
        },
        static_cast<stuntdouble::PresentationMode>(${PRESENTATION[s.presentation]}),
        static_cast<stuntdouble::AutonomyMode>(${autoIdx(s)}),
        ${hasAuto(s) ? 'true' : 'false'}, ${s.behaviors},
        ${s.waypoint ? 'true' : 'false'}, stuntdouble::Vec3{${num(s.waypoint?.x ?? 0)}, ${num(s.waypoint?.y ?? 0)}, ${num(s.waypoint?.z ?? 0)}}
    }`;
    })
    .join(',\n');

  return `// <auto-generated>Stuntdouble conformance fixtures — regenerate with: node packages/conformance/gen-fixtures.mjs</auto-generated>
// Copyright (c) 2026 Yusuf Günay. Licensed under MPL-2.0.
#pragma once
#include <string>
#include <vector>
#include "stuntdouble/stunt_brain.hpp"

namespace stuntdouble::conformance {

struct ScenarioFixture {
    std::string id;
    BehaviorProfile profile;
    EntitySnapshot self;
    std::vector<EntitySnapshot> hostiles;
    PresentationMode presentation;
    AutonomyMode autonomy;   // legacy preset (valid when has_autonomy)
    bool has_autonomy;
    int behaviors;           // resolved flag mask
    bool has_waypoint{false};
    Vec3 waypoint{};
};

inline const std::vector<ScenarioFixture>& fixtures() {
    static const std::vector<ScenarioFixture> all = {
${blocks}
    };
    return all;
}

} // namespace stuntdouble::conformance
`;
}

function luaEntity(e) {
  const p = e.position;
  const v = e.velocity ?? { x: 0, y: 0, z: 0 };
  return (
    `{ id = ${JSON.stringify(e.id)}, position = { x = ${num(p.x)}, y = ${num(p.y)}, z = ${num(p.z)} }, ` +
    `velocity = { x = ${num(v.x)}, y = ${num(v.y)}, z = ${num(v.z)} }, healthRatio = ${num(e.healthRatio)}, ` +
    `staminaRatio = ${num(e.staminaRatio)}, isAttacking = ${e.isAttacking ? 'true' : 'false'}, ` +
    `isWindUp = ${e.isWindUp ? 'true' : 'false'}, isRanged = ${e.isRanged ? 'true' : 'false'}, ${e.projectileEta ? `projectileEta = ${num(e.projectileEta)}, ` : ''}threatWeight = ${num(e.threatWeight)} }`
  );
}

function emitLua() {
  const blocks = scenarios
    .map((s) => {
      const p = s.profile;
      const hostiles = s.hostiles.length ? '\n      ' + s.hostiles.map(luaEntity).join(',\n      ') + '\n    ' : '';
      return `  {
    id = ${JSON.stringify(s.id)},
    profile = { id = ${JSON.stringify(p.id)}, name = ${JSON.stringify(p.name ?? 'Protagonist')}, aggression = ${num(p.aggression)}, discipline = ${num(p.discipline)}, cinematicFlair = ${num(p.cinematicFlair)}, reactionDelayMs = ${p.reactionDelayMs}, preferredRange = ${num(p.preferredRange)} },
    self = ${luaEntity(s.self)},
    hostiles = {${hostiles}},
    presentation = ${PRESENTATION[s.presentation]},
    autonomy = ${hasAuto(s) ? autoIdx(s) : 'nil'},
    behaviors = ${s.behaviors},
    hasWaypoint = ${s.waypoint ? 'true' : 'false'},
    waypoint = { x = ${num(s.waypoint?.x ?? 0)}, y = ${num(s.waypoint?.y ?? 0)}, z = ${num(s.waypoint?.z ?? 0)} }
  }`;
    })
    .join(',\n');

  return `-- <auto-generated>Stuntdouble conformance fixtures — regenerate with: node packages/conformance/gen-fixtures.mjs</auto-generated>
-- Copyright (c) 2026 Yusuf Günay. Licensed under MPL-2.0.
return {
${blocks}
}
`;
}

// ---------------------------------------------------------------------------
// Expected decisions (from expected.json) as native literals, so runners need no JSON parser.
// ---------------------------------------------------------------------------
const expected = JSON.parse(readFileSync(join(FIXTURES, 'expected.json'), 'utf8'));
const lit = (v) => (v === null || v === undefined ? null : JSON.stringify(v));
const HEADER = 'Stuntdouble conformance expected decisions — regenerate with: node packages/conformance/gen-fixtures.mjs';

function emitExpectedCs() {
  const rows = expected
    .map(
      (e) => `            new ExpectedDecision
            {
                Id = ${lit(e.id)}, Stance = ${lit(e.stance)}, Intercept = ${csBool(e.interceptHumanInput)},
                Utility = ${lit(e.selectedUtilityAction)}, Score = ${num(e.utilityScore)},
                Plan = new string[] { ${e.goapPlan.map(lit).join(', ')} },
                Command = ${lit(e.immediateCommand)}, Sx = ${num(e.steering[0])}, Sz = ${num(e.steering[1])},
                Speed = ${num(e.speedMultiplier)}, CamMode = ${lit(e.camera.mode)}, TimeScale = ${num(e.camera.timeScale)},
                Fov = ${num(e.camera.fovMultiplier)}, Focus = ${e.camera.focusTargetId === null ? 'null' : lit(e.camera.focusTargetId)}
            }`
    )
    .join(',\n');
  return `// <auto-generated>${HEADER}</auto-generated>
// Copyright (c) 2026 Yusuf Günay. Licensed under MPL-2.0.
namespace Stuntdouble.Conformance
{
    public sealed class ExpectedDecision
    {
        public string Id, Stance, Utility, Command, CamMode, Focus;
        public bool Intercept;
        public double Score, Sx, Sz, Speed, TimeScale, Fov;
        public string[] Plan;
    }

    public static class Expected
    {
        public static readonly ExpectedDecision[] All =
        {
${rows}
        };
    }
}
`;
}

function emitExpectedCpp() {
  const rows = expected
    .map(
      (e) => `    stuntdouble::conformance::ExpectedDecision{
        ${lit(e.id)}, ${lit(e.stance)}, ${e.interceptHumanInput ? 'true' : 'false'},
        ${lit(e.selectedUtilityAction)}, ${num(e.utilityScore)},
        std::vector<std::string>{ ${e.goapPlan.map(lit).join(', ')} },
        ${lit(e.immediateCommand)}, ${num(e.steering[0])}, ${num(e.steering[1])},
        ${num(e.speedMultiplier)}, ${lit(e.camera.mode)}, ${num(e.camera.timeScale)},
        ${num(e.camera.fovMultiplier)}, ${e.camera.focusTargetId === null ? 'false' : 'true'}, ${e.camera.focusTargetId === null ? '""' : lit(e.camera.focusTargetId)}
    }`
    )
    .join(',\n');
  return `// <auto-generated>${HEADER}</auto-generated>
// Copyright (c) 2026 Yusuf Günay. Licensed under MPL-2.0.
#pragma once
#include <string>
#include <vector>

namespace stuntdouble::conformance {

struct ExpectedDecision {
    std::string id, stance;
    bool intercept;
    std::string utility;
    double score;
    std::vector<std::string> plan;
    std::string command;
    double sx, sz, speed;
    std::string cam_mode;
    double time_scale, fov;
    bool has_focus;
    std::string focus;
};

inline const std::vector<ExpectedDecision>& expected() {
    static const std::vector<ExpectedDecision> all = {
${rows}
    };
    return all;
}

} // namespace stuntdouble::conformance
`;
}

function emitExpectedLua() {
  const rows = expected
    .map(
      (e) => `  {
    id = ${lit(e.id)}, stance = ${lit(e.stance)}, intercept = ${e.interceptHumanInput ? 'true' : 'false'},
    utility = ${lit(e.selectedUtilityAction)}, score = ${num(e.utilityScore)},
    plan = { ${e.goapPlan.map(lit).join(', ')} },
    command = ${lit(e.immediateCommand)}, sx = ${num(e.steering[0])}, sz = ${num(e.steering[1])},
    speed = ${num(e.speedMultiplier)}, camMode = ${lit(e.camera.mode)}, timeScale = ${num(e.camera.timeScale)},
    fov = ${num(e.camera.fovMultiplier)}, focus = ${e.camera.focusTargetId === null ? 'nil' : lit(e.camera.focusTargetId)}
  }`
    )
    .join(',\n');
  return `-- <auto-generated>${HEADER}</auto-generated>
-- Copyright (c) 2026 Yusuf Günay. Licensed under MPL-2.0.
return {
${rows}
}
`;
}

writeFileSync(join(FIXTURES, 'fixtures.cs'), emitCs(), 'utf8');
writeFileSync(join(FIXTURES, 'fixtures.hpp'), emitCpp(), 'utf8');
writeFileSync(join(FIXTURES, 'fixtures.lua'), emitLua(), 'utf8');

writeFileSync(join(FIXTURES, 'expected.cs'), emitExpectedCs(), 'utf8');
writeFileSync(join(FIXTURES, 'expected.hpp'), emitExpectedCpp(), 'utf8');
writeFileSync(join(FIXTURES, 'expected.lua'), emitExpectedLua(), 'utf8');

console.log(`[conformance] generated ${scenarios.length} native fixtures (cs / hpp / lua)`);
